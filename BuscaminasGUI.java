    int[][] palestino = new int[10][10];
    JButton[][] botones = new JButton[10][10];
    JLabel resultado;

    public BuscaminasGUI() {
        //ventana
        setTitle("Buscaminas");
        setSize(600, 500);
        setDefaultCloseOperation(JFrame.EXIT_ON_CLOSE);
        setLayout(new BorderLayout());

        //pan sup
        JPanel panelSuperior = new JPanel();

        //titulo
        JLabel titulo = new JLabel("BUSCAMINAS");

        //bomba
        JLabel minas = new JLabel("Minas: 10");

        panelSuperior.add(titulo);
        panelSuperior.add(minas);

        //pan centro
        JPanel panelCentral = new JPanel();

        panelCentral.setLayout(new GridBagLayout());
        GridBagConstraints gbc = new GridBagConstraints();

        //boton
        gbc.fill = GridBagConstraints.BOTH;
        //dila
        gbc.weightx = 1;
        gbc.weighty = 1;

        //funciones panel centra
        //10x10
        for (int fila = 0; fila < 10; fila++) {
            for (int columna = 0; columna < 10; columna++) {

                JButton boton = new JButton();
                boton.setPreferredSize(new Dimension(50, 50));

                botones[fila][columna] = boton;

                gbc.gridx = columna;
                gbc.gridy = fila;

                panelCentral.add(boton, gbc);

                final int filaBoton = fila;
                final int columnaBoton = columna;

                boton.addActionListener(new ActionListener() {
                    @Override
                    public void actionPerformed(ActionEvent e) {
                        pulsarCasiila(boton, filaBoton, columnaBoton);
                    }
                });
            }
        }

        //pan inf
        JPanel panelInferior = new JPanel();

        JButton nuevaPartida = new JButton("Nueva partida");

        resultado = new JLabel("Partida en curso");

        panelInferior.add(nuevaPartida);
        panelInferior.add(resultado);

        //funcionalidad
        add(panelSuperior, BorderLayout.NORTH);
        add(panelCentral, BorderLayout.CENTER);
        add(panelInferior, BorderLayout.SOUTH);

        //botones
        colocarBombas();

        nuevaPartida.addActionListener(e -> {
            dispose();
            new BuscaminasGUI().setVisible(true);
        });
    }

    private void colocarBombas() {
        int bombasColocadas = 0;

        while (bombasColocadas < 10) {
            int fila = (int) (Math.random() * 10);
            int columna = (int) (Math.random() * 10);

            if (palestino[fila][columna] == 0) {
                palestino[fila][columna] = 1;
                bombasColocadas++;
            }
        }
    }

    private void pulsarCasiila(JButton boton, int fila, int columna) {

        if (palestino[fila][columna] == 1) {

            boton.setText("X");
            boton.setBackground(new Color(180, 0, 0));
            boton.setForeground(Color.WHITE);

            resultado.setText("Has perdido. Pulsa Nueva Partida");

            for (int i = 0; i < 10; i++) {
                for (int j = 0; j < 10; j++) {

                    if (palestino[i][j] == 1) {
                        botones[i][j].setText("X");
                        botones[i][j].setBackground(new Color(180, 0, 0));
                        botones[i][j].setForeground(Color.WHITE);
                    }

                    botones[i][j].setEnabled(false);
                }
            }

        } else {

            int bombasCerca = 0;

            for (int i = fila - 1; i <= fila + 1; i++) {
                for (int j = columna - 1; j <= columna + 1; j++) {

                    if (i >= 0 && i < 10 && j >= 0 && j < 10) {

                        if (palestino[i][j] == 1) {
                            bombasCerca++;
                        }
                    }
                }
            }

            if (bombasCerca > 0) {
                boton.setText(String.valueOf(bombasCerca));
            } else {
                boton.setText("");
            }
        }

        boton.setEnabled(false);
    }

    

